-- DATE_FUNC2(CDATETIME, 'DATETIME') -> 'YYYY-MM-DD HH24:MI:SS'
-- DATE_FUNC2(CDATETIME, 'DATE') -> 'YYYY-MM-DD'
-- DATE_FUNC2(CDATETIME, 'TIME') -> 'HH24:MI:SS'

CREATE OR REPLACE FUNCTION DATE_FUNC2(I_DATE IN DATE, I_KEY IN VARCHAR2)
RETURN VARCHAR2
IS
    O_DATE VARCHAR2(100);
BEGIN
    IF I_KEY = 'DATETIME' THEN
        O_DATE := TO_CHAR(I_DATE, 'YYYY-MM-DD HH24:MI:SS');
    ELSIF I_KEY = 'DATE' THEN
        O_DATE := TO_CHAR(I_DATE, 'YYYY-MM-DD');
    ELSIF I_KEY = 'TIME' THEN
        O_DATE := TO_CHAR(I_DATE, 'HH24:MI:SS');
    ELSE
        O_DATE := '값 잘못 입력했음ㅋ';
    END IF;
    
    RETURN O_DATE;
END;
/

SELECT 
    DATE_FUNC2(CDATETIME,'DATETIME') || '  ',
    DATE_FUNC2(CDATETIME,'DATE') || '  ',
    DATE_FUNC2(CDATETIME,'TIME') 
FROM TBL_BOARD;

ROLLBACK;

-- GRADE_FUNC
-- GRADE_FUNC(ENR_GRADE)
-- ENR_GRADE 값이 90 이상이면 'A' 리턴
-- ENR_GRADE 값이 80 이상이면 'B' 리턴
-- ENR_GRADE 값이 70 이상이면 'C' 리턴
-- ENR_GRADE 값이 60 이상이면 'D' 리턴
-- 그외에는 'F'리턴

CREATE OR REPLACE FUNCTION GRADE_FUNC (I_GRADE IN NUMBER)
RETURN VARCHAR2 
IS
BEGIN
    IF I_GRADE > 100 OR I_GRADE < 0 THEN
    RETURN '잘못된 숫자 입력';
    ELSIF I_GRADE >= 90 THEN
        RETURN 'A';
    ELSIF I_GRADE >= 80 THEN
        RETURN 'B';
     ELSIF I_GRADE >= 70 THEN
        RETURN 'C';
    ELSIF I_GRADE >= 60 THEN
        RETURN 'D';
    ELSE 
        RETURN 'F';
     END IF;
END;
/

SELECT ENR_GRADE,GRADE_FUNC(ENR_GRADE) 
FROM 
ENROL;

