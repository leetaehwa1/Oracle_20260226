-- GENDER_FUNC(JUMIN)
-- 7번째 숫자가 1이랑 3이면 남자 리턴
-- 2,4 면 여자 리턴
-- 인자값이 13자리가 아니면 '제대로 값 입력하셈' 리턴
CREATE OR REPLACE FUNCTION GENDER_FUNC(I_JUMIN IN VARCHAR2)
RETURN VARCHAR2 
IS
    O_GENDER CHAR(1);
BEGIN
    IF LENGTH(I_JUMIN)!= 13 THEN
    RETURN '제대로 된 값 입력하세요';
    END IF;
    
    O_GENDER := SUBSTR(I_JUMIN,7,1);
    IF O_GENDER IN ('1','3') THEN    
       RETURN '남자';
    ELSIF O_GENDER IN('2','4') THEN
        RETURN '여자';
    ELSE 
        RETURN '외국인';
    END IF;
END;
/
SELECT JUMIN, GENDER_FUNC(JUMIN)
FROM STU;

