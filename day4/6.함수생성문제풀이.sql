CREATE OR REPLACE FUNCTION DATE_FUNC(I_DATE IN DATE)
RETURN VARCHAR2
IS

BEGIN
    RETURN TO_CHAR(I_DATE, 'YYYY-MM-DD HH24:MI:SS');
END;
/


