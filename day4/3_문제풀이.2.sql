-- 1. 남자이면서(주민번호 7번째자리 1) 공과대학에 속한 학생의 수를 구하시오.
SELECT COUNT(*) AS 학생수
FROM STU S
INNER JOIN DEPARTMENT D1 ON S.DEPTNO1 = D1.DEPTNO
INNER JOIN DEPARTMENT D2 ON D1.PART = D2.DEPTNO
WHERE SUBSTR(JUMIN,7,1) = '1' AND D2.DNAME = '공과대학';

-- 2. 학생들의 아이디의 마지막 세글자를 '*' 로 채우시오
SELECT
    RPAD(SUBSTR(ID, 1, LENGTH(ID)-3), LENGTH(ID), '*') ID,
    SUBSTR(ID, 1, LENGTH(ID)-3) || '***'
FROM STU;

-- 3. 보너스+급여가 400 이하인 교수들의 이름, 아이디, 학과명을 출력하시오.

SELECT NAME, ID, D.DNAME
FROM PROFESSOR P
INNER JOIN DEPARTMENT D ON P.DEPTNO = D.DEPTNO
WHERE PAY+NVL(BONUS,0) <= 400
GROUP BY PROFNO,NAME,ID,D.DNAME;

-- 4. 담당 학생이 2명이상인 교수의 이름, 아이디, 담당학생 수를 출력하시오.

SELECT P.NAME,
       P.ID,
       COUNT(S.STUNO) AS 담당학생수
FROM PROFESSOR P
LEFT JOIN STU S ON P.PROFNO = S.PROFNO
GROUP BY P.PROFNO, P.NAME, P.ID
HAVING COUNT(S.STUNO) >= 2;