--NVL로 대체되는 인자값의 타입은 같은 타입이어야함.

SELECT STU_NAME, NVL(TO_CHAR(AVG(ENR_GRADE)), '점수 없음')
FROM STUDENT S 
LEFT JOIN ENROL E ON S.STU_NO = E.STU_NO
GROUP BY STU_NAME
;

