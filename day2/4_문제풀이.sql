-- 사번, 이름, 자신의 부하직원 수 출력
SELECT MGR, COUNT(*)
FROM EMP
WHERE MGR IS NOT NULL
GROUP BY MGR;

SELECT EMPNO,ENAME,NVL(CNT, 0) AS CNT
FROM EMP E
LEFT JOIN(
    SELECT MGR, COUNT(*)AS CNT
    FROM EMP
    WHERE MGR IS NOT NULL
    GROUP BY MGR
)T ON T.MGR = E.EMPNO
ORDER BY CNT DESC
;

