-- 셀프 조인(SELF JOIN)
SELECT *
FROM EMP;

SELECT E1.EMPNO, E1.ENAME, E2.ENAME AS MANAGER
FROM EMP E1
INNER JOIN EMP E2 ON E1.MGR = E2.EMPNO 
;

