SELECT PROFNO,NAME, D1.DNAME 학과 , D2.DNAME 학부 ,D3.DNAME 대학
FROM PROFESSOR P 
INNER JOIN DEPARTMENT D1 ON P.DEPTNO = D1.DEPTNO
