SELECT TITLE, 댓글개수
FROM(
    SELECT TITLE, COUNT(*) AS 댓글개수 ,1 AS ORDERKEY
    FROM TBL_BOARD B 
    INNER JOIN TBL_COMMENT C ON B.BOARDNO = C.BOARDNO
    GROUP BY B.BOARDNO, TITLE
    UNION
    SELECT '댓글전체개수',COUNT(*), 2 AS ORDERKEY
    FROM TBL_COMMENT
    ORDER BY ORDERKEY, 댓글개수 DESC
);


