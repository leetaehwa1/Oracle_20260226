-- 작성한 게시글의 조회수 합이 가장 많은 상위 3명의 이름과 조회수 합 출력

SELECT USERID, SUM(CNT) AS SUM_CNT
FROM TBL_BOARD
GROUP BY USERID
ORDER BY SUM_CNT DESC
;

SELECT USERNAME,SUM_CNT
FROM(
    SELECT USERID, SUM(CNT) AS SUM_CNT
    FROM TBL_BOARD
    GROUP BY USERID
    ORDER BY SUM_CNT DESC

)T
INNER JOIN TBL_USER U ON T.USERID = U.USERID
WHERE ROWNUM <= 3
;

